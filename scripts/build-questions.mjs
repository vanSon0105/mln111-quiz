import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(projectRoot, "MLN111_598_cau_nguyen_ban.txt");
const outputPath = resolve(projectRoot, "questions.js");

function collectMarkers(text, pattern) {
  const normalizeLetter = (letter) =>
    ({ "В": "B", "в": "B", "С": "C", "с": "C" })[letter] || letter.toUpperCase();

  const matches = [...text.matchAll(pattern)].map((match) => ({
    letter: normalizeLetter(match[1]),
    start: match.index + match[0].search(/[A-Ea-eВСвс]/),
    contentStart: match.index + match[0].length,
  }));

  let bestSequence = [];

  matches.forEach((marker, startIndex) => {
    if (marker.letter !== "A") return;

    const sequence = [marker];
    let expectedCode = "B".charCodeAt(0);

    for (let index = startIndex + 1; index < matches.length; index += 1) {
      const expected = String.fromCharCode(expectedCode);
      if (matches[index].letter === expected) {
        sequence.push(matches[index]);
        expectedCode += 1;
      }
    }

    if (sequence.length > bestSequence.length) bestSequence = sequence;
  });

  return bestSequence;
}

function parseLine(line, index) {
  const tabIndex = line.lastIndexOf("\t");
  if (tabIndex === -1) return null;

  const body = line.slice(0, tabIndex).trim();
  const answerBlock = line.slice(tabIndex + 1).trim();
  const answerMatch = answerBlock.match(/^([A-Ea-e]+)(?:\s+([\s\S]*))?$/);
  if (!answerMatch) return null;

  const answer = [...answerMatch[1].toUpperCase()];
  const markerPatterns = [
    /(?:^|\s)([A-Ea-eВСвс])\s*(?:\.|\))\s+/g,
    /(?:^|\s)([A-Ea-eВСвс])\s*(?:\.|\))/g,
    /(?:^|\s)([A-Ea-eВСвс])(?:\s*(?:\.|\)))?\s+/g,
  ];

  let markers = [];
  for (const pattern of markerPatterns) {
    markers = collectMarkers(body, pattern);
    if (markers.length >= 2) break;
  }

  if (markers.length < 2) return null;

  const options = markers.map((marker, markerIndex) => ({
    id: marker.letter,
    text: body
      .slice(
        marker.contentStart,
        markerIndex + 1 < markers.length ? markers[markerIndex + 1].start : body.length,
      )
      .trim(),
  }));

  const optionIds = new Set(options.map((option) => option.id));
  if (!answer.every((letter) => optionIds.has(letter))) return null;

  const rawExplanation = (answerMatch[2] || "").trim();
  const explanation = rawExplanation.replace(/^\((.*)\)$/s, "$1").trim();

  return {
    id: index + 1,
    question: body.slice(0, markers[0].start).trim(),
    options,
    answer,
    explanation,
  };
}

const source = readFileSync(sourcePath, "utf8");
const lines = source.split(/\r?\n/).filter((line) => line.trim());
const parsedLines = lines.map(parseLine);
const questions = parsedLines.filter(Boolean);
const skippedLines = parsedLines
  .map((question, index) => (question ? null : index + 1))
  .filter(Boolean);

const output = `// Generated by scripts/build-questions.mjs.\nwindow.QUIZ_QUESTIONS = ${JSON.stringify(questions, null, 2)};\n`;
writeFileSync(outputPath, output, "utf8");

console.log(
  `Generated ${questions.length} questions (${skippedLines.length} skipped: ${skippedLines.join(", ")}).`,
);
